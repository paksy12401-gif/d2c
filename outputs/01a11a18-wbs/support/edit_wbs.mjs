import fs from 'node:fs/promises';
import path from 'node:path';
import { FileBlob, SpreadsheetFile } from '@oai/artifact-tool';

const dir = import.meta.dirname;
const workbook = await SpreadsheetFile.importXlsx(await FileBlob.load(path.join(dir,'..','MDA_WBS_수정본.xlsx')));
const sheet = workbook.worksheets.getItem('WBS');
const sourceView = await workbook.render({sheetName:'WBS',range:'A1:AQ18',scale:1,format:'png'});
await fs.writeFile(path.join(dir,'before_daily.png'),new Uint8Array(await sourceView.arrayBuffer()));
const day = 86400000;
const epoch = Date.UTC(1899,11,30);
const serial = iso => (Date.parse(`${iso}T00:00:00Z`)-epoch)/day;
const oldStart=serial('2023-05-03'), oldEnd=serial('2023-06-16');
const first=serial('2026-10-06'), last=serial('2026-11-06');
const original=sheet.getRange('E9:F47').values;
const mapped=original.map(row=>row.map(value=>{
  if(value===null || value==='') return null;
  const n=typeof value==='number'?value:(Date.parse(value)-epoch)/day;
  if(!Number.isFinite(n)) throw new Error(`Unexpected date ${value}`);
  return first+Math.round((n-oldStart)*(last-first)/(oldEnd-oldStart));
}));
sheet.getRange('E9:F47').values=mapped;
sheet.getRange('E9:F47').setNumberFormat('yyyy-mm-dd');
sheet.getRange('H3').values=[[1]];
sheet.getRange('A4').values=[['시작일·마감일 수정 시 해당 날짜 칸의 색상이 자동 반영됩니다. 주말 포함 1칸 = 1일입니다.']];
sheet.getRange('I5').values=[['2026년 10월 6일 ~ 11월 6일 · 하루 단위 일정 (주말 포함)']];
const col=n=>{let result='';for(let x=n;x>0;x=Math.floor((x-1)/26))result=String.fromCharCode(65+(x-1)%26)+result;return result;};
sheet.getRange('I7:AQ7').clear({applyTo:'contents'});
sheet.getRange('I7').formulas=[['=DATE(2026,10,6)']];
sheet.getRange('J7:AN7').formulas=[Array.from({length:31},(_,i)=>`=${col(9+i)}7+1`)];
sheet.getRange('I7:AN7').setNumberFormat('d');
for(const merge of ['I6:M6','N6:R6','S6:W6','X6:AB6','AC6:AG6','AH6:AL6','AM6:AQ6']) sheet.unmergeCells(merge);
sheet.getRange('I6:AQ6').clear({applyTo:'contents'});
sheet.mergeCells('I6:AH6');sheet.mergeCells('AI6:AN6');
sheet.getRange('I6').values=[['2026년 10월']];
sheet.getRange('AI6').values=[['2026년 11월']];
sheet.getRange('I6:AH6').format.fill='#2F75B5';
sheet.getRange('AI6:AN6').format.fill='#45818E';
sheet.getRange('I6:AN6').format.font={name:'Malgun Gothic',size:10,bold:true,color:'#FFFFFF'};
sheet.getRange('I6:AN6').format.horizontalAlignment='center';
sheet.getRange('AO6:AQ7').format.fill='#FFFFFF';
const grid=sheet.getRange('I9:AQ47');
grid.conditionalFormats.deleteAll();
const base='ISNUMBER($E9),ISNUMBER($F9),ISNUMBER(I$7),$F9>=$E9,$E9<=I$7,$F9>=I$7';
const palette=[['팀원 전체','#548DD4'],['김성준','#D99594'],['이원석','#632423'],['문홍식','#B2A1C7'],['김태훈','#3F3151']];
for(const [owner,color] of palette) grid.conditionalFormats.addCustom(`AND(${base},$C9="${owner}")`,{fill:color});
grid.conditionalFormats.addCustom(`AND(${base},ISNUMBER(SEARCH(",",$C9)))`,{fill:'#B6D7A8'});
grid.conditionalFormats.addCustom(`AND(${base},NOT(ISNUMBER(SEARCH(",",$C9))),$C9<>"팀원 전체",$C9<>"김성준",$C9<>"이원석",$C9<>"문홍식",$C9<>"김태훈")`,{fill:'#548DD4'});
workbook.recalculate();
const dates=sheet.getRange('I7:AN7').values[0];
if(dates.length!==32 || dates[0]!==first || dates[31]!==last || dates.some((d,i)=>d!==first+i)) throw new Error('Daily timeline verification failed');
if(Math.min(...mapped.flat().filter(v=>v!==null))!==first || Math.max(...mapped.flat().filter(v=>v!==null))!==last) throw new Error('Task schedule boundaries incorrect');
console.log((await workbook.inspect({kind:'table',range:'WBS!E29:G32',include:'values,formulas',maxChars:1600})).ndjson);
console.log((await workbook.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!|#SPILL!|#CALC!',options:{useRegex:true,maxResults:30},maxChars:1000})).ndjson);
const preview=await workbook.render({sheetName:'WBS',range:'A1:AQ47',scale:1,format:'png'});
await fs.writeFile(path.join(dir,'daily.png'),new Uint8Array(await preview.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(workbook)).save(path.join(dir,'..','MDA_WBS_20261006-20261106.xlsx'));
console.log('Exported daily WBS; 32 consecutive days verified.');
